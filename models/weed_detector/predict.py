import os
import argparse
import cv2
from ultralytics import YOLO

def run_inference(image_path, model_path, output_path):
    if not os.path.exists(image_path):
        print(f"Error: Input image '{image_path}' not found.")
        return

    # Check if the model exists at the provided path, otherwise check relative to this script
    if not os.path.exists(model_path):
        script_dir = os.path.dirname(os.path.abspath(__file__))
        model_path = os.path.join(script_dir, 'best.pt')
        if not os.path.exists(model_path):
            print(f"Error: Model file '{model_path}' not found.")
            return

    print(f"Loading YOLO model from: {model_path}")
    model = YOLO(model_path)

    print(f"Running inference on: {image_path}")
    results = model.predict(source=image_path, imgsz=640, conf=0.25, save=False)

    if not results:
        print("No results generated by the model.")
        return

    result = results[0]
    annotated_image = result.plot()

    cv2.imwrite(output_path, annotated_image)
    print(f"Success! Annotated image saved to: {output_path}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Standalone Weed Detection Testing Script")
    parser.add_argument("-i", "--image", required=True, help="Path to the input crop field image")
    parser.add_argument("-m", "--model", default="best.pt", help="Path to the trained YOLOv8 best.pt file")
    parser.add_argument("-o", "--output", default="predicted_output.jpg", help="Path to save the annotated output image")
    
    args = parser.parse_args()
    run_inference(args.image, args.model, args.output)